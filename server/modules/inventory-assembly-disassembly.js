// INV-17 — Inventory Assembly / Disassembly.
//
// Frozen by `solution.md §27.27` (Domain 5 Closure Design) and
// `docs/requirements/inventory-warehouse.md §32.3.3` (INV-17):
//   - Engineering / BOM is the STRUCTURE source. Inventory owns only the
//     physical consume / produce movement. This module NEVER builds a second
//     BOM truth: the component structure is read from the canonical
//     Engineering resolver `resolveEffectiveBomForCaller`.
//   - Every physical stock change goes through `applyInventoryMutation`
//     (INV-07 canonical mutation contract).
//   - Status lifecycle: DRAFT → CONFIRMED. A confirmed document can never be
//     confirmed twice.
//   - `assertFinancialPeriodsOpen` is honoured for the business date.
//
// The document number is generated by this module (`ASM-...` for assembly,
// `DSA-...` for disassembly).

import { transaction, id as genId } from '../db.js';
import { audit } from '../lib/audit.js';
import { HttpError, allow, allowAny, assertAllowedFields, readJson, send } from '../lib/http.js';
import { applyInventoryMutation } from '../lib/inventory-mutation.js';
import { resolveEffectiveBomForCaller } from './engineering-bom.js';
import { assertFinancialPeriodsOpen } from './financial-inventory.js';

const SOURCE_ASSEMBLY = 'INVENTORY_ASSEMBLY';
const SOURCE_DISASSEMBLY = 'INVENTORY_DISASSEMBLY';

// The engineering BOM `purpose` enum is (GENERAL | SELF_MAKE | OUTSOURCE).
// Design §27.27 names the assembly purpose as 'INVENTORY_ASSEMBLY'; that value
// is not a legal `boms.purpose`, so it is tried first (the resolver falls
// back to a purpose-agnostic legacy lookup) and the legal self-make / general
// purposes are used as the deterministic fallbacks.
const BOM_PURPOSE_CANDIDATES = Object.freeze(['SELF_MAKE', 'GENERAL', 'INVENTORY_ASSEMBLY']);

function nowIso() { return new Date().toISOString(); }

function ensureTable(db) {
  db.exec(`
    CREATE TABLE IF NOT EXISTS inventory_assembly_orders (
      id TEXT PRIMARY KEY,
      doc_no TEXT NOT NULL UNIQUE,
      order_type TEXT NOT NULL CHECK(order_type IN ('ASSEMBLY','DISASSEMBLY')),
      status TEXT NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','CONFIRMED','CANCELLED')),
      production_order_id TEXT,
      warehouse_id TEXT NOT NULL REFERENCES warehouses(id),
      product_id TEXT NOT NULL REFERENCES products(id),
      quantity REAL NOT NULL CHECK(quantity > 0),
      business_date TEXT NOT NULL,
      bom_id TEXT,
      bom_version TEXT,
      bom_effective_from TEXT,
      remark TEXT NOT NULL DEFAULT '',
      created_by TEXT NOT NULL REFERENCES users(id),
      confirmed_by TEXT REFERENCES users(id),
      created_at TEXT NOT NULL,
      confirmed_at TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_inventory_assembly_orders_type ON inventory_assembly_orders(order_type, status);
    CREATE INDEX IF NOT EXISTS idx_inventory_assembly_orders_production ON inventory_assembly_orders(production_order_id);
    CREATE TABLE IF NOT EXISTS inventory_assembly_order_items (
      id TEXT PRIMARY KEY,
      order_id TEXT NOT NULL REFERENCES inventory_assembly_orders(id),
      line_no INTEGER NOT NULL,
      component_product_id TEXT NOT NULL REFERENCES products(id),
      bom_quantity REAL NOT NULL,
      scrap_rate REAL NOT NULL DEFAULT 0,
      required_quantity REAL NOT NULL,
      consumed_quantity REAL NOT NULL DEFAULT 0,
      produced_quantity REAL NOT NULL DEFAULT 0,
      lot_id TEXT,
      serial_id TEXT,
      bin_id TEXT,
      created_at TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS idx_inventory_assembly_order_items_order ON inventory_assembly_order_items(order_id);
  `);
}

function generateDocNo(orderType) {
  const prefix = orderType === 'ASSEMBLY' ? 'ASM' : 'DSA';
  const stamp = Date.now().toString(36).toUpperCase();
  const rand = Math.floor(Math.random() * 1296).toString(36).toUpperCase().padStart(2, '0');
  return `${prefix}-${stamp}-${rand}`;
}

function normalizeBusinessDate(value) {
  const text = String(value ?? '').trim();
  if (!text) return nowIso().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(text)) throw new HttpError(400, '业务日期格式应为 YYYY-MM-DD');
  return text;
}

// Resolve the canonical Engineering BOM. `resolveEffectiveBomForCaller` is the
// single BOM truth; this module never queries `bom_items` on its own authority
// for the STRUCTURE — it only reads the component lines of the BOM the
// resolver selected.
function resolveBom(db, productId, businessDate) {
  for (const purpose of BOM_PURPOSE_CANDIDATES) {
    const bom = resolveEffectiveBomForCaller(db, productId, purpose, businessDate);
    if (bom) return bom;
  }
  return null;
}

function loadBomComponents(db, bom) {
  const rows = db.prepare(`
    SELECT id, product_id productId, quantity, scrap_rate scrapRate, line_no lineNo
      FROM bom_items
     WHERE bom_id=?
     ORDER BY line_no, id
  `).all(bom.id);
  return rows.map((row) => ({
    id: row.id,
    productId: row.productId,
    bomQuantity: Number(row.quantity),
    scrapRate: Number(row.scrapRate || 0),
    lineNo: Number(row.lineNo),
  }));
}

// The consumed / produced quantity of one component line follows the BOM
// ratio times the document quantity. Scrap rate is applied to the REQUIRED
// (physical) quantity so that a scrapped portion is still physically issued —
// Inventory owns the physical movement; Finance owns the cost of the scrap.
function requiredQuantityFor(bomQuantity, scrapRate, orderQuantity) {
  const base = Number(bomQuantity) * Number(orderQuantity);
  const scrap = Number(scrapRate || 0);
  return base * (1 + (Number.isFinite(scrap) ? scrap : 0));
}

function assertWarehouseExists(db, warehouseId) {
  const row = db.prepare('SELECT id, active, bin_enabled FROM warehouses WHERE id=?').get(warehouseId);
  if (!row) throw new HttpError(400, `仓库 ${warehouseId} 不存在`);
  if (!row.active) throw new HttpError(409, `仓库 ${warehouseId} 已停用`);
  return row;
}

function assertProductExists(db, productId) {
  const row = db.prepare('SELECT id, code, name, active FROM products WHERE id=?').get(productId);
  if (!row) throw new HttpError(400, `产品 ${productId} 不存在`);
  if (!row.active) throw new HttpError(409, `产品 ${productId} 已停用`);
  return row;
}

function readDoc(db, id) {
  const doc = db.prepare('SELECT * FROM inventory_assembly_orders WHERE id=?').get(id);
  if (!doc) throw new HttpError(404, '组装拆卸单不存在');
  return doc;
}

function readItems(db, orderId) {
  return db.prepare(`
    SELECT * FROM inventory_assembly_order_items
     WHERE order_id=?
     ORDER BY line_no, id
  `).all(orderId);
}

// Pre-flight availability check over the canonical `inventory` positions.
// The consumed quantity is aggregated per component so that a component
// spread over several positions is judged as a whole.
function assertDocumentStockAvailable(db, doc, items, orderType) {
  const requiredByProduct = new Map();
  if (orderType === 'DISASSEMBLY') {
    // The assembled parent is consumed ONCE for the whole document.
    requiredByProduct.set(doc.product_id, Number(doc.quantity));
  } else {
    for (const item of items) {
      const productId = item.component_product_id;
      requiredByProduct.set(
        productId,
        (requiredByProduct.get(productId) || 0) + Number(item.required_quantity),
      );
    }
  }
  for (const [productId, required] of requiredByProduct) {
    if (!Number.isFinite(required) || required <= 0) {
      throw new HttpError(409, `单据组件 ${productId} 的应耗数量无效`);
    }
    const row = db.prepare(`
      SELECT COALESCE(SUM(quantity), 0) q
        FROM inventory
       WHERE product_id=? AND warehouse_id=? AND active=1
    `).get(productId, doc.warehouse_id);
    const available = Number(row?.q || 0);
    if (available < required) {
      throw new HttpError(409, `库存不足：${productId} 在仓库 ${doc.warehouse_id} 可用 ${available}，需出 ${required}`, {
        code: 'ASSEMBLY_STOCK_INSUFFICIENT',
        resolution: '请先补足该位置库存，或减少单据数量。',
      });
    }
  }
}

function toCamelDoc(doc, items) {
  return {
    id: doc.id,
    docNo: doc.doc_no,
    orderType: doc.order_type,
    status: doc.status,
    productionOrderId: doc.production_order_id ?? null,
    warehouseId: doc.warehouse_id,
    productId: doc.product_id,
    quantity: Number(doc.quantity),
    businessDate: doc.business_date,
    bomId: doc.bom_id ?? null,
    bomVersion: doc.bom_version ?? null,
    bomEffectiveFrom: doc.bom_effective_from ?? null,
    remark: doc.remark || '',
    createdBy: doc.created_by,
    confirmedBy: doc.confirmed_by ?? null,
    createdAt: doc.created_at,
    confirmedAt: doc.confirmed_at ?? null,
    items: items.map((item) => ({
      id: item.id,
      lineNo: Number(item.line_no),
      componentProductId: item.component_product_id,
      bomQuantity: Number(item.bom_quantity),
      scrapRate: Number(item.scrap_rate),
      requiredQuantity: Number(item.required_quantity),
      consumedQuantity: Number(item.consumed_quantity),
      producedQuantity: Number(item.produced_quantity),
      lotId: item.lot_id ?? null,
      serialId: item.serial_id ?? null,
      binId: item.bin_id ?? null,
    })),
  };
}

async function createDocument(db, req, res, actor, orderType) {
  allow(actor, 'INVENTORY_ASSEMBLY_MANAGE');
  const body = await readJson(req);
  assertAllowedFields(body, [
    'productionOrderId', 'warehouseId', 'productId', 'quantity',
    'components', 'businessDate', 'remark',
  ]);

  const warehouseId = String(body.warehouseId ?? '').trim();
  if (!warehouseId) throw new HttpError(400, '仓库必填');
  const productId = String(body.productId ?? '').trim();
  if (!productId) throw new HttpError(400, '产品必填');
  const orderQuantity = Number(body.quantity);
  if (!Number.isFinite(orderQuantity) || orderQuantity <= 0) throw new HttpError(400, '数量必须为正数');

  const businessDate = normalizeBusinessDate(body.businessDate);
  assertWarehouseExists(db, warehouseId);
  assertProductExists(db, productId);

  const productionOrderId = body.productionOrderId ? String(body.productionOrderId).trim() : null;
  if (productionOrderId) {
    const po = db.prepare('SELECT id FROM production_orders WHERE id=?').get(productionOrderId);
    if (!po) throw new HttpError(400, `生产订单 ${productionOrderId} 不存在`);
  }

  // Structural truth is the canonical Engineering BOM. Any component list the
  // client sends is IGNORED on purpose (fail-closed against a forged BOM).
  const bom = resolveBom(db, productId, businessDate);
  if (!bom) {
    throw new HttpError(409, `产品 ${productId} 没有可用的生效 BOM，无法${orderType === 'ASSEMBLY' ? '组装' : '拆卸'}`, {
      code: 'ASSEMBLY_BOM_UNAVAILABLE',
      resolution: '请先在工程域维护并批准该产品的生效 BOM。',
    });
  }
  const components = loadBomComponents(db, bom);
  if (!components.length) {
    throw new HttpError(409, `产品 ${productId} 的 BOM ${bom.version || bom.id} 没有组件行`, {
      code: 'ASSEMBLY_BOM_EMPTY',
    });
  }
  for (const component of components) {
    assertProductExists(db, component.productId);
  }

  const id = genId();
  const docNo = generateDocNo(orderType);
  const now = nowIso();
  transaction(db, () => {
    ensureTable(db);
    db.prepare(`
      INSERT INTO inventory_assembly_orders(
        id, doc_no, order_type, status, production_order_id, warehouse_id, product_id,
        quantity, business_date, bom_id, bom_version, bom_effective_from, remark,
        created_by, created_at)
      VALUES(?, ?, ?, 'DRAFT', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(
      id, docNo, orderType, productionOrderId, warehouseId, productId,
      orderQuantity, businessDate, bom.id, bom.version ?? null, bom.effective_from ?? null,
      body.remark ? String(body.remark) : '', actor.id, now,
    );
    const insertItem = db.prepare(`
      INSERT INTO inventory_assembly_order_items(
        id, order_id, line_no, component_product_id, bom_quantity, scrap_rate,
        required_quantity, consumed_quantity, produced_quantity, lot_id, serial_id, bin_id, created_at)
      VALUES(?, ?, ?, ?, ?, ?, ?, 0, 0, NULL, NULL, NULL, ?)
    `);
    components.forEach((component, index) => {
      insertItem.run(
        genId(), id, index + 1, component.productId, component.bomQuantity, component.scrapRate,
        requiredQuantityFor(component.bomQuantity, component.scrapRate, orderQuantity), now,
      );
    });
    audit(db, actor.id, 'CREATE', 'INVENTORY_ASSEMBLY_ORDER', id, `Create ${orderType} ${docNo}`);
  });
  return send(res, 201, toCamelDoc(readDoc(db, id), readItems(db, id)));
}

export async function createAssemblyOrder(db, req, res, actor) {
  return createDocument(db, req, res, actor, 'ASSEMBLY');
}

export async function createDisassemblyOrder(db, req, res, actor) {
  return createDocument(db, req, res, actor, 'DISASSEMBLY');
}

// The confirm path applies the physical movement. It is protected against a
// double apply by three independent mechanisms:
//   1. the document status gate (`DRAFT` → `CONFIRMED`, second confirm is
//      refused with 409);
//   2. the canonical mutation idempotency key, which is derived from the
//      document id + line id and therefore replays instead of re-applying;
//   3. the `inventory_mutation_log` row written by `applyInventoryMutation`.
function confirmDocument(db, res, actor, id, orderType) {
  allow(actor, 'INVENTORY_ASSEMBLY_MANAGE');
  ensureTable(db);
  const doc = readDoc(db, id);
  if (doc.order_type !== orderType) {
    throw new HttpError(409, `单据类型 ${doc.order_type} 与当前操作不匹配`);
  }
  if (doc.status !== 'DRAFT') {
    throw new HttpError(409, `单据状态 ${doc.status} 不可重复确认`, {
      code: 'ASSEMBLY_ALREADY_CONFIRMED',
      resolution: '已确认的单据不会重复产生物理移动。',
    });
  }

  const businessDate = doc.business_date;
  // Financial period gate — the document business date must be open.
  assertFinancialPeriodsOpen(db, businessDate);

  const items = readItems(db, id);
  if (!items.length) throw new HttpError(409, '单据没有组件行，无法确认');

  const sourceType = orderType === 'ASSEMBLY' ? SOURCE_ASSEMBLY : SOURCE_DISASSEMBLY;
  const docQuantity = Number(doc.quantity);
  const now = nowIso();
  const movementGroupId = `${sourceType}:${id}`;

  // Pre-flight availability check. Every mutation below opens its OWN
  // transaction (SQLite forbids nested transactions on the same handle), so a
  // late "insufficient stock" failure could otherwise leave a partially
  // applied document. The check below proves the whole document is covered
  // BEFORE the first movement is applied; `applyInventoryMutation` remains the
  // authoritative writer and re-verifies the same bound.
  assertDocumentStockAvailable(db, doc, items, orderType);

  // Each mutation opens its own transaction (SQLite forbids nested
  // transactions on the same handle), so the document status flip and the
  // movement are guarded by the mutation idempotency key, not by an outer
  // transaction. The status gate above refuses a second confirm before any
  // movement is attempted.
  for (const item of items) {
    const required = Number(item.required_quantity);
    if (!Number.isFinite(required) || required <= 0) {
      throw new HttpError(409, `组件行 ${item.line_no} 的应耗数量无效`);
    }
    if (orderType === 'ASSEMBLY') {
      // Consume the component (OUT) …
      applyInventoryMutation({
        db,
        sourceType,
        sourceId: id,
        sourceItemId: item.id,
        sourceNo: doc.doc_no,
        businessDate,
        actor: { id: actor.id },
        movementKind: 'OUT',
        quantity: required,
        fromPosition: {
          productId: item.component_product_id,
          warehouseId: doc.warehouse_id,
          binId: item.bin_id ?? null,
          ownerType: 'ENTERPRISE',
          ownerId: null,
          stockStatus: 'AVAILABLE',
          lotId: item.lot_id ?? null,
          serialId: item.serial_id ?? null,
        },
        toPosition: null,
        movementGroupId,
        idempotencyKey: `${sourceType}:${id}:${item.id}:ISSUE`,
        remark: `Assembly component issue ${doc.doc_no}`,
      });
      // … and produce the assembly (IN) once for the whole document.
    }
    // Disassembly consumes the assembled parent ONCE for the whole document
    // (below) and receives every component back (further below).
  }

  if (orderType === 'DISASSEMBLY') {
    // Consume the assembled parent exactly once for the whole document.
    applyInventoryMutation({
      db,
      sourceType,
      sourceId: id,
      sourceItemId: `${id}:PRODUCED`,
      sourceNo: doc.doc_no,
      businessDate,
      actor: { id: actor.id },
      movementKind: 'OUT',
      quantity: docQuantity,
      fromPosition: {
        productId: doc.product_id,
        warehouseId: doc.warehouse_id,
        binId: null,
        ownerType: 'ENTERPRISE',
        ownerId: null,
        stockStatus: 'AVAILABLE',
        lotId: null,
        serialId: null,
      },
      toPosition: null,
      movementGroupId,
      idempotencyKey: `${sourceType}:${id}:PRODUCED:ISSUE`,
      remark: `Disassembly issue ${doc.doc_no}`,
    });
  }

  if (orderType === 'ASSEMBLY') {
    // Produce the assembled parent exactly once for the document.
    applyInventoryMutation({
      db,
      sourceType,
      sourceId: id,
      sourceItemId: `${id}:PRODUCED`,
      sourceNo: doc.doc_no,
      businessDate,
      actor: { id: actor.id },
      movementKind: 'IN',
      quantity: docQuantity,
      toPosition: {
        productId: doc.product_id,
        warehouseId: doc.warehouse_id,
        binId: null,
        ownerType: 'ENTERPRISE',
        ownerId: null,
        stockStatus: 'AVAILABLE',
        lotId: null,
        serialId: null,
      },
      movementGroupId,
      idempotencyKey: `${sourceType}:${id}:PRODUCED:RECEIPT`,
      remark: `Assembly receipt ${doc.doc_no}`,
    });
  } else {
    // Receive every component back once.
    for (const item of items) {
      applyInventoryMutation({
        db,
        sourceType,
        sourceId: id,
        sourceItemId: `${item.id}:PRODUCED`,
        sourceNo: doc.doc_no,
        businessDate,
        actor: { id: actor.id },
        movementKind: 'IN',
        quantity: Number(item.required_quantity),
        toPosition: {
          productId: item.component_product_id,
          warehouseId: doc.warehouse_id,
          binId: item.bin_id ?? null,
          ownerType: 'ENTERPRISE',
          ownerId: null,
          stockStatus: 'AVAILABLE',
          lotId: item.lot_id ?? null,
          serialId: item.serial_id ?? null,
        },
        movementGroupId,
        idempotencyKey: `${sourceType}:${id}:${item.id}:RECEIPT`,
        remark: `Disassembly receipt ${doc.doc_no}`,
      });
    }
  }

  // Record the movement result on the document lines, then flip the status.
  transaction(db, () => {
    ensureTable(db);
    for (const item of items) {
      if (orderType === 'ASSEMBLY') {
        db.prepare(`UPDATE inventory_assembly_order_items SET consumed_quantity=required_quantity WHERE id=?`).run(item.id);
      } else {
        db.prepare(`UPDATE inventory_assembly_order_items SET produced_quantity=required_quantity WHERE id=?`).run(item.id);
      }
    }
    const updated = db.prepare(`SELECT status FROM inventory_assembly_orders WHERE id=?`).get(id);
    if (updated.status !== 'DRAFT') {
      throw new HttpError(409, `单据状态 ${updated.status} 不可重复确认`, {
        code: 'ASSEMBLY_ALREADY_CONFIRMED',
      });
    }
    db.prepare(`UPDATE inventory_assembly_orders SET status='CONFIRMED', confirmed_by=?, confirmed_at=? WHERE id=?`)
      .run(actor.id, now, id);
    audit(db, actor.id, 'CONFIRM', 'INVENTORY_ASSEMBLY_ORDER', id, `Confirm ${orderType} ${doc.doc_no}`);
  });

  return send(res, 200, toCamelDoc(readDoc(db, id), readItems(db, id)));
}

export function confirmAssemblyOrder(db, req, res, actor, id) {
  return confirmDocument(db, res, actor, id, 'ASSEMBLY');
}

export function confirmDisassemblyOrder(db, req, res, actor, id) {
  return confirmDocument(db, res, actor, id, 'DISASSEMBLY');
}

export function listAssemblyOrders(db, res, actor, url) {
  allowAny(actor, ['INVENTORY_ASSEMBLY_VIEW', 'INVENTORY_ASSEMBLY_MANAGE']);
  ensureTable(db);
  const params = [];
  const where = ['1=1'];
  const productionOrderId = url.searchParams.get('productionOrderId');
  if (productionOrderId) { where.push('production_order_id=?'); params.push(productionOrderId); }
  const orderType = url.searchParams.get('orderType');
  if (orderType) { where.push('order_type=?'); params.push(String(orderType).toUpperCase()); }
  const rows = db.prepare(`
    SELECT * FROM inventory_assembly_orders
     WHERE ${where.join(' AND ')}
     ORDER BY created_at DESC, id DESC
     LIMIT 500
  `).all(...params);
  const orders = rows.map((doc) => toCamelDoc(doc, readItems(db, doc.id)));
  return send(res, 200, { assemblyOrders: orders });
}
